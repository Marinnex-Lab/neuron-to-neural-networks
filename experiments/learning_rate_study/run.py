"""Controlled learning-rate study on a held-out split.

Run from the repository root:
    python experiments/learning_rate_study/run.py

Design (stated before the run, see docs/experiment_design.md):
- Independent variable: learning rate in {0.05, 0.2, 0.5, 2.0, 8.0}.
- Controls: data (fixed seed), architecture (2 -> 4 -> 1), steps (1500), full-batch GD,
  initialization scheme. Only the learning rate changes.
- Repetitions: initialization seeds 0..4 for each learning rate.
- Metrics: validation loss and validation accuracy, on data never used for training.
- Decision rule: prefer the learning rate with the lowest mean validation loss, but only
  among settings where no run diverged (non-finite loss).

Outputs written by this script:
    results/learning_rate_study.json
    reports/learning_rate_study.md
    assets/plots/learning_rate_study.png
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib

import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from mlp import init_network  # noqa: E402

LEARNING_RATES = [0.05, 0.2, 0.5, 2.0, 8.0]
INIT_SEEDS = [0, 1, 2, 3, 4]
STEPS = 1500
HIDDEN = 4
DATA_SEED = 123


def make_data(seed: int, n: int) -> tuple[np.ndarray, np.ndarray]:
    """Label is 1 inside a circle of radius sqrt(1.5), with 5% label noise."""
    rng = np.random.default_rng(seed)
    X = rng.uniform(-2.0, 2.0, size=(n, 2))
    y = (X[:, 0] ** 2 + X[:, 1] ** 2 < 1.5).astype(float)
    flip = rng.random(n) < 0.05
    y[flip] = 1.0 - y[flip]
    return X, y


def run_study() -> list[dict[str, object]]:
    X_train, y_train = make_data(DATA_SEED, 120)
    X_val, y_val = make_data(DATA_SEED + 1, 120)
    rows = []
    for lr in LEARNING_RATES:
        for seed in INIT_SEEDS:
            net = init_network(2, HIDDEN, seed=seed)
            history = net.fit(X_train, y_train, lr=lr, steps=STEPS)
            val_loss = net.batch_loss(X_val, y_val)
            diverged = not np.isfinite(val_loss) or not np.isfinite(history[-1])
            rows.append({
                "learning_rate": lr,
                "seed": seed,
                "train_loss": history[-1],
                "val_loss": float(val_loss) if np.isfinite(val_loss) else None,
                "val_accuracy": net.accuracy(X_val, y_val),
                "diverged": bool(diverged),
            })
    return rows


def summarize(rows: list[dict[str, object]]) -> list[dict[str, object]]:
    out = []
    for lr in LEARNING_RATES:
        group = [r for r in rows if r["learning_rate"] == lr]
        vloss = np.array([r["val_loss"] for r in group if r["val_loss"] is not None], dtype=float)
        vacc = np.array([r["val_accuracy"] for r in group], dtype=float)
        tloss = np.array([r["train_loss"] for r in group], dtype=float)
        out.append({
            "learning_rate": lr,
            "train_loss_mean": float(tloss.mean()),
            "val_loss_mean": float(vloss.mean()) if vloss.size else None,
            "val_loss_sd": float(vloss.std()) if vloss.size else None,
            "val_acc_mean": float(vacc.mean()),
            "val_acc_sd": float(vacc.std()),
            "diverged_runs": sum(1 for r in group if r["diverged"]),
        })
    return out


def choose(summary: list[dict[str, object]]) -> float | None:
    eligible = [s for s in summary if s["diverged_runs"] == 0 and s["val_loss_mean"] is not None]
    if not eligible:
        return None
    return float(min(eligible, key=lambda s: s["val_loss_mean"])["learning_rate"])  # type: ignore[arg-type]


def write_report(summary: list[dict[str, object]], chosen: float | None, path: Path) -> None:
    lines = [
        "# Learning-rate study: results",
        "",
        "Generated by `experiments/learning_rate_study/run.py`. Do not edit by hand; re-run the script.",
        "",
        f"Data: circle task, 120 training and 120 validation points, 5% label noise. "
        f"Architecture 2 -> {HIDDEN} -> 1, {STEPS} full-batch steps, initialization seeds {INIT_SEEDS}.",
        "",
        "| Learning rate | Train loss (mean) | Validation loss (mean ± sd) | Validation accuracy (mean ± sd) | Diverged runs |",
        "|---|---|---|---|---|",
    ]
    for s in summary:
        vl = "n/a" if s["val_loss_mean"] is None else f"{s['val_loss_mean']:.4f} ± {s['val_loss_sd']:.4f}"
        lines.append(
            f"| {s['learning_rate']} | {s['train_loss_mean']:.4f} | {vl} | "
            f"{s['val_acc_mean']:.3f} ± {s['val_acc_sd']:.3f} | {s['diverged_runs']} / {len(INIT_SEEDS)} |"
        )
    slowest = summary[0]
    lines += [
        "",
        f"Decision rule result: {'learning rate ' + str(chosen) if chosen is not None else 'no eligible setting'}.",
        "",
        "## Interpretation",
        "",
        "- The comparison uses held-out validation data, not training data.",
        f"- At learning rate {slowest['learning_rate']} the mean training loss after {STEPS} steps is "
        f"{slowest['train_loss_mean']:.4f}, so that setting has not converged within this step budget. "
        "Part of the difference between learning rates is therefore speed, not final quality.",
        "- Five seeds give a rough spread, not a confidence interval.",
        "- The result applies to this dataset, this architecture and this step count only.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def plot(summary: list[dict[str, object]], path: Path) -> None:
    lrs = [s["learning_rate"] for s in summary]
    means = [s["val_loss_mean"] if s["val_loss_mean"] is not None else np.nan for s in summary]
    sds = [s["val_loss_sd"] if s["val_loss_sd"] is not None else np.nan for s in summary]
    fig, ax = plt.subplots(figsize=(6.5, 4))
    ax.errorbar(lrs, means, yerr=sds, marker="o", capsize=4)
    ax.set_xscale("log")
    ax.set_xlabel("learning rate (log scale)")
    ax.set_ylabel("validation loss (mean ± sd over 5 seeds)")
    ax.set_title("Learning rate vs validation loss (held-out data)")
    ax.grid(True, which="both")
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def main() -> None:
    rows = run_study()
    summary = summarize(rows)
    chosen = choose(summary)
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "reports").mkdir(exist_ok=True)
    (ROOT / "assets" / "plots").mkdir(parents=True, exist_ok=True)
    (ROOT / "results" / "learning_rate_study.json").write_text(
        json.dumps({"summary": summary, "runs": rows, "chosen_learning_rate": chosen}, indent=2),
        encoding="utf-8")
    write_report(summary, chosen, ROOT / "reports" / "learning_rate_study.md")
    plot(summary, ROOT / "assets" / "plots" / "learning_rate_study.png")
    for s in summary:
        vl = "n/a" if s["val_loss_mean"] is None else f"{s['val_loss_mean']:.4f}"
        print(f"lr={s['learning_rate']}: val loss {vl}, val acc {s['val_acc_mean']:.3f}, diverged {s['diverged_runs']}")
    print("chosen learning rate:", chosen)


if __name__ == "__main__":
    # Select the file-only backend only when run as a script. Importing this module from a
    # notebook must not change the notebook's plotting backend.
    matplotlib.use("Agg")
    main()
