"""Train one perceptron on AND, OR and XOR; save results and a figure.

Run from the repository root:
    python experiments/logic_gates.py

Outputs (generated by this run, not typed by hand):
    results/logic_gates.json
    reports/experiment_results.md
    assets/plots/logic_gates.png
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # no window; write files only
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from numpy.typing import NDArray  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from perceptron import Perceptron  # noqa: E402

LEARNING_RATE = 0.1
EPOCHS = 20

X: NDArray[np.float64] = np.array([[0, 0], [0, 1], [1, 0], [1, 1]], dtype=np.float64)
GATES: dict[str, NDArray[np.int64]] = {
    "AND": np.array([0, 0, 0, 1]),
    "OR": np.array([0, 1, 1, 1]),
    "XOR": np.array([0, 1, 1, 0]),
}


def run_gate(name: str, y: NDArray[np.int64]) -> dict[str, object]:
    model = Perceptron(n_features=2, learning_rate=LEARNING_RATE, epochs=EPOCHS).fit(X, y)
    return {
        "gate": name,
        "learning_rate": LEARNING_RATE,
        "epochs": EPOCHS,
        "weights": model.weights.tolist(),
        "bias": float(model.bias),
        "predictions": model.predict(X).tolist(),
        "targets": y.tolist(),
        "accuracy": model.accuracy(X, y),
        "errors_per_epoch": model.errors_per_epoch,
    }


def plot_boundaries(results: list[dict[str, object]], path: Path) -> None:
    fig, axes = plt.subplots(1, 3, figsize=(13, 4.2))
    xs = np.linspace(-0.5, 1.5, 100)
    for ax, r in zip(axes, results):
        w = np.array(r["weights"])  # type: ignore[arg-type]
        b = float(r["bias"])  # type: ignore[arg-type]
        y = np.array(r["targets"])  # type: ignore[arg-type]
        ax.scatter(X[:, 0], X[:, 1], c=y, cmap="coolwarm", s=150, edgecolors="black", zorder=3)
        if abs(w[1]) > 1e-10:
            ax.plot(xs, -(w[0] * xs + b) / w[1], "k--", label="decision boundary")
        elif abs(w[0]) > 1e-10:
            ax.axvline(-b / w[0], color="k", ls="--", label="decision boundary")
        ax.set_xlim(-0.5, 1.5)
        ax.set_ylim(-0.5, 1.5)
        ax.set_title(f"{r['gate']}: accuracy {r['accuracy']:.0%}")
        ax.set_xlabel("x1")
        ax.set_ylabel("x2")
        ax.grid(True)
        ax.legend(fontsize=8, loc="upper right")
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def write_report(results: list[dict[str, object]], path: Path) -> None:
    lines = [
        "# Experiment results: single perceptron on AND, OR, XOR",
        "",
        "Generated by `experiments/logic_gates.py`. Do not edit by hand; re-run the script.",
        "",
        f"Settings: learning_rate = {LEARNING_RATE}, epochs = {EPOCHS}, zero initialization, "
        "deterministic sample order (no randomness).",
        "",
        "| Gate | Accuracy | Learned weights | Learned bias | Mistakes per epoch |",
        "|---|---|---|---|---|",
    ]
    for r in results:
        w = ", ".join(f"{v:.4g}" for v in r["weights"])  # type: ignore[union-attr]
        lines.append(
            f"| {r['gate']} | {r['accuracy']:.0%} | [{w}] | {r['bias']:.4g} | "
            f"{r['errors_per_epoch']} |"
        )
    lines += [
        "",
        "## Interpretation",
        "",
        "- AND and OR are linearly separable: the perceptron reaches 0 mistakes and stays there.",
        "- XOR is not linearly separable (see docs/learning_roadmap.md, Module 3). The mistake "
        "count never reaches 0, so accuracy stays below 100%.",
        "- Observations are limited to these runs and this learning rate. They are not a general "
        "claim about perceptron training.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    results = [run_gate(name, y) for name, y in GATES.items()]

    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "reports").mkdir(exist_ok=True)
    (ROOT / "assets" / "plots").mkdir(parents=True, exist_ok=True)

    (ROOT / "results" / "logic_gates.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    write_report(results, ROOT / "reports" / "experiment_results.md")
    plot_boundaries(results, ROOT / "assets" / "plots" / "logic_gates.png")

    for r in results:
        print(f"{r['gate']}: accuracy={r['accuracy']:.0%}  mistakes={r['errors_per_epoch']}")


if __name__ == "__main__":
    main()
