"""Train two-layer networks on XOR across hidden widths and random seeds.

Run from the repository root:
    python experiments/multilayer_network/run.py

Settings are fixed in this file: learning rate 0.5, 3000 full-batch steps,
seeds 0..19, widths 2, 3, 4. Outputs are written, not typed by hand:
    results/multilayer_xor.json
    reports/multilayer_results.md
    assets/plots/multilayer_xor_loss.png
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from mlp import init_network  # noqa: E402

X = np.array([[0, 0], [0, 1], [1, 0], [1, 1]], dtype=float)
Y = np.array([0, 1, 1, 0], dtype=float)

LEARNING_RATE = 0.5
STEPS = 3000
SEEDS = list(range(20))
WIDTHS = [2, 3, 4]


def run_all() -> list[dict[str, object]]:
    rows = []
    for width in WIDTHS:
        for seed in SEEDS:
            net = init_network(2, width, seed=seed)
            history = net.fit(X, Y, lr=LEARNING_RATE, steps=STEPS)
            rows.append({
                "hidden_units": width,
                "seed": seed,
                "final_loss": history[-1],
                "accuracy": net.accuracy(X, Y),
                # Loss every 50 steps (STEPS is a multiple of 50); the full history would be ~5 MB.
                "loss_every_50_steps": history[::50],
            })
    return rows


def summarize(rows: list[dict[str, object]]) -> list[dict[str, object]]:
    out = []
    for width in WIDTHS:
        group = [r for r in rows if r["hidden_units"] == width]
        solved = sum(1 for r in group if r["accuracy"] == 1.0)
        losses = np.array([r["final_loss"] for r in group], dtype=float)
        out.append({
            "hidden_units": width,
            "solved": solved,
            "runs": len(group),
            "median_final_loss": float(np.median(losses)),
        })
    return out


def write_report(summary: list[dict[str, object]], path: Path) -> None:
    lines = [
        "# Multilayer network on XOR: results",
        "",
        "Generated by `experiments/multilayer_network/run.py`. Do not edit by hand; re-run the script.",
        "",
        f"Settings: full-batch gradient descent, learning rate {LEARNING_RATE}, {STEPS} steps, "
        f"seeds {SEEDS[0]}..{SEEDS[-1]}, sigmoid units, binary cross-entropy, "
        "uniform initialization (seeded).",
        "",
        "| Hidden units | Runs solving XOR (accuracy 100%) | Median final loss |",
        "|---|---|---|",
    ]
    for s in summary:
        lines.append(f"| {s['hidden_units']} | {s['solved']} / {s['runs']} | {s['median_final_loss']:.4f} |")
    lines += [
        "",
        "## Interpretation",
        "",
        "- A single perceptron cannot solve XOR (see the logic-gates experiment).",
        "- With a hidden layer, the same XOR data is solved by gradient descent for most seeds.",
        "- Success depends on the random start: some runs with 2 hidden units get stuck, "
        "so the number of successes is reported, not only the best run.",
        "- These results are for one dataset, one learning rate and one step count. They do not "
        "establish how often this works for other problems.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def plot_curves(rows: list[dict[str, object]], path: Path) -> None:
    fig, ax = plt.subplots(figsize=(7, 4))
    for width in WIDTHS:
        for r in [r for r in rows if r["hidden_units"] == width][:5]:
            steps = list(range(0, STEPS + 1, 50))
            ax.plot(steps, r["loss_every_50_steps"], color=f"C{WIDTHS.index(width)}", alpha=0.6,
                    label=f"{width} hidden" if r["seed"] == 0 else None)
    ax.set_xlabel("gradient step")
    ax.set_ylabel("training loss (BCE)")
    ax.set_yscale("log")
    ax.set_title("XOR training: first 5 seeds per width")
    ax.grid(True, which="both")
    ax.legend()
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def main() -> None:
    rows = run_all()
    summary = summarize(rows)
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "reports").mkdir(exist_ok=True)
    (ROOT / "assets" / "plots").mkdir(parents=True, exist_ok=True)
    (ROOT / "results" / "multilayer_xor.json").write_text(
        json.dumps({"summary": summary, "runs": rows}, indent=2), encoding="utf-8")
    write_report(summary, ROOT / "reports" / "multilayer_results.md")
    plot_curves(rows, ROOT / "assets" / "plots" / "multilayer_xor_loss.png")
    for s in summary:
        print(f"hidden={s['hidden_units']}: solved {s['solved']}/{s['runs']}, median final loss {s['median_final_loss']:.4f}")


if __name__ == "__main__":
    main()
